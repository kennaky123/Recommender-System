function makeEpisodes(
  prefix: string,
  seasonsCount: number,
  perSeason: number,
  runtimeMinutes: number,
  backdropUrl: string,
  titles: string[]
): Episode[] {
  const episodes: Episode[] = [];
  for (let s = 1; s <= seasonsCount; s++) {
    for (let e = 1; e <= perSeason; e++) {
      const idx = ((s - 1) * perSeason + (e - 1)) % titles.length;
      episodes.push({
        season: s,
        episode: e,
        title: titles[idx],
        runtimeMinutes,
        synopsis: `S${s} EP${e}: ${prefix} — Crew telemetry locks onto an uncharted anomaly as the orbital window narrows and survival depends on precision.`,
        backdropUrl,
      });
    }
  }
  return episodes;
}

